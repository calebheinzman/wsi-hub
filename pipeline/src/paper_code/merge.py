_DATASET_NAME_HINTS: str | None = None


def _get_dataset_name_hints(max_items: int = 200) -> str:
    global _DATASET_NAME_HINTS
    if _DATASET_NAME_HINTS is not None:
        return _DATASET_NAME_HINTS

    names: list[str] = []
    seen = set()

    def _add(name: str) -> None:
        n = (name or '').strip()
        if not n:
            return
        if n.lower() in seen:
            return
        seen.add(n.lower())
        names.append(n)

    try:
        premade_csv = Path('pipeline/config/supp/initial_dataset_list.csv')
        if premade_csv.exists():
            rows = premade_csv.read_text(encoding='utf-8').splitlines()
            if rows:
                hdr = rows[0].lower()
                start = 1 if ('dataset' in hdr or ',' in hdr or 'slug' in hdr) else 0
                for r in rows[start:]:
                    if len(names) >= max_items:
                        break
                    raw = (r.split(',')[0] or '').strip()
                    if raw:
                        _add(raw)
    except Exception:
        pass

    try:
        public_list = Path('pipeline/config/supp/public_dataset_list.txt')
        if public_list.exists():
            for line in public_list.read_text(encoding='utf-8').splitlines():
                if len(names) >= max_items:
                    break
                _add(line)
    except Exception:
        pass

    if names:
        _DATASET_NAME_HINTS = '\n'.join(f'- {n}' for n in names[:max_items])
    else:
        _DATASET_NAME_HINTS = ''
    return _DATASET_NAME_HINTS


def _inject_dataset_hints_into_prompt(prompt_template: str) -> str:
    hints = _get_dataset_name_hints()
    if not hints:
        return prompt_template
    return (
        (prompt_template or '')
        + "\n\nKnown dataset names (reference list):\n"
        + hints
        + "\n\nUse this list only to recognize dataset mentions in the paper text. Do not copy dataset names into labels.\n"
    )

def summarize_and_extract(items: list[dict], prompts: list[str], prompts_dir: Path, out: Path, use_gemini: bool = False, use_batch: bool = False) -> list[dict]:
    """
    Summarizes and extracts information from a list of papers using a series of LLM prompts.

    This function processes each paper with a set of specified prompts, parallelizing the workload
    across multiple processes. The extracted data from each prompt is stored in the 'extraction' field
    of the paper's record.

    Args:
        items: A list of paper records (dictionaries), each expected to have a 'fulltext' field.
        prompts: A list of prompt filenames to be executed for each paper.
        prompts_dir: The base directory where the prompt files are located.
        out: The file path to save the enriched list of paper records.
        use_gemini: If True, use Gemini API instead of OpenAI.
        use_batch: If True, use batch API for LLM calls.

    Returns:
        A list of paper records, where each record is updated with an 'extraction' field
        containing the data generated by the LLM prompts.
    """
    # 32 processes (~250 MB each, 8 GB): bounded by this laptop's memory, not OpenAI's
    # limits (32 use ~1.5M of the 180M tokens a minute allowed).
    procs = int(os.getenv("WSI_POOL_PROCS", "32"))
    procs = max(1, procs)
    serial_threshold = int(os.getenv("WSI_POOL_SERIAL_THRESHOLD", "2"))
    # Announce stage with counts for clearer console separation
    try:
        print(f"Summarize & extract — processing {len(items)} items...")
    except Exception:
        pass

    # Batch mode: process all prompts for all items via batch API
    if use_batch:
        # Initialize result skeleton
        results = [item.copy() for item in items]
        for rec in results:
            if 'extraction' not in rec:
                rec['extraction'] = {}

        # Prepare items with fulltext once
        items_with_text: list[tuple[int, str]] = []
        for i, item in enumerate(items):
            fulltext = item.get('fulltext', '')
            if fulltext:
                items_with_text.append((i, fulltext))

        if not items_with_text:
            return results

        # Choose model once (per provider)
        if use_gemini:
            model_name = os.getenv('WSI_EXTRACTION_MODEL', 'gemini-2.5-pro')
        else:
            model_name = os.getenv('WSI_EXTRACTION_MODEL', 'gpt-6-luna')

        # Batch processor for this provider
        processor = BatchProcessor(provider="gemini" if use_gemini else "gpt")

        # One batch containing every request for every prompt.
        # Use custom_id format: "{item_idx}:{prompt_name}"
        all_requests = []
        prompt_list = []  # Track which prompts we're processing
        
        for prompt_name in prompts:
            prompt_path = prompts_dir / prompt_name
            if not prompt_path.exists():
                print(f"Warning: Prompt file {prompt_path} not found.")
                continue

            prompt_template = prompt_path.read_text(encoding="utf-8")
            if prompt_name == 'paper_classification_prompt.md':
                prompt_template = _inject_dataset_hints_into_prompt(prompt_template)
            prompt_list.append(prompt_name)

            # Build requests for this prompt
            for idx, text in items_with_text:
                all_requests.append({
                    'custom_id': f"{idx}:{prompt_name}",  # Combined key
                    'system_prompt': prompt_template,
                    'user_prompt': text,
                    'model': model_name,
                    'response_format': {'type': 'json_object'},
                })

        if not all_requests:
            return results

        # Submit single batch containing all extraction requests
        print(f"Submitting single batch for {len(prompt_list)} prompts × {len(items_with_text)} items = {len(all_requests)} total requests...")
        
        # Use get_or_create_batch which handles caching, resumption, and polling
        batch_results = processor.get_or_create_batch(
            requests=all_requests,
            step_name="extract_all_prompts",
            model=model_name,
            metadata={"description": f"All extraction prompts: {', '.join(prompt_list)}"},
        )

        # Parse and validate results, tracking failures for retry
        failed_items: list[tuple[str, int, str, str]] = []  # (prompt_name, idx, text, custom_id)
        
        for prompt_name in prompt_list:
            prompt_path = prompts_dir / prompt_name
            prompt_template = prompt_path.read_text(encoding="utf-8") if prompt_path.exists() else ""
            reject_all_empty = prompt_name != "dataset_details.md"
            
            for idx, text in items_with_text:
                custom_id = f"{idx}:{prompt_name}"
                result = batch_results.get(custom_id)
                content = _extract_batch_content(result, use_gemini)
                
                extracted_json = {}
                if content:
                    is_valid, parsed, error = validate_json_response(
                        content, 
                        reject_all_empty=reject_all_empty
                    )
                    if is_valid and parsed:
                        extracted_json = parsed
                    else:
                        logger.warning(f"Invalid JSON for {custom_id}: {error}")
                        failed_items.append((prompt_name, idx, text, prompt_template))
                else:
                    logger.warning(f"No content for {custom_id}")
                    failed_items.append((prompt_name, idx, text, prompt_template))
                
                results[idx]['extraction'][prompt_name] = extracted_json
        
        # Retry failed items (up to 2 additional attempts)
        max_retries = int(os.getenv('WSI_BATCH_RETRIES', '2'))
        for retry_attempt in range(max_retries):
            if not failed_items:
                break
            
            logger.info(f"Retry attempt {retry_attempt + 1}/{max_retries} for {len(failed_items)} failed extraction items")
            
            # Build retry batch
            retry_requests = []
            for prompt_name, idx, text, prompt_template in failed_items:
                retry_requests.append({
                    'custom_id': f"{idx}:{prompt_name}",
                    'system_prompt': prompt_template,
                    'user_prompt': text,
                    'model': model_name,
                    'response_format': {'type': 'json_object'},
                })
            
            # Submit retry batch
            retry_results = processor.get_or_create_batch(
                requests=retry_requests,
                step_name=f"extract_all_prompts_retry{retry_attempt + 1}",
                model=model_name,
                metadata={"description": f"Retry {retry_attempt + 1} for failed extractions"},
            )
            
            # Process retry results
            next_failed_items = []
            for prompt_name, idx, text, prompt_template in failed_items:
                reject_all_empty = prompt_name != "dataset_details.md"
                custom_id = f"{idx}:{prompt_name}"
                result = retry_results.get(custom_id)
                content = _extract_batch_content(result, use_gemini)
                
                if content:
                    is_valid, parsed, error = validate_json_response(
                        content,
                        reject_all_empty=reject_all_empty
                    )
                    if is_valid and parsed:
                        results[idx]['extraction'][prompt_name] = parsed
                        continue
                    else:
                        logger.warning(f"Retry {retry_attempt + 1} - Invalid JSON for {custom_id}: {error}")
                else:
                    logger.warning(f"Retry {retry_attempt + 1} - No content for {custom_id}")
                
                next_failed_items.append((prompt_name, idx, text, prompt_template))
            
            failed_items = next_failed_items
        
        if failed_items:
            logger.warning(f"Extraction completed with {len(failed_items)} items still failing after retries")
        
        return results

    # Each finished paper is checkpointed under the output's name (1.4, 1.6c and the
    # backfill write different files), and a paper whose calls raised is retried.
    from pipeline.src.checkpoint import fingerprint, process_runner, run_items
    from .dedupe import dedupe_key
    workers = 1 if len(items) <= serial_threshold else procs
    model = os.getenv('WSI_EXTRACTION_MODEL', 'gemini-2.5-pro' if use_gemini else 'gpt-6-luna')
    prompt_texts = [(prompts_dir / p).read_text(encoding="utf-8") if (prompts_dir / p).exists() else "" for p in prompts]
    prompt_texts = [_inject_dataset_hints_into_prompt(t) if p == 'paper_classification_prompt.md' else t
                    for p, t in zip(prompts, prompt_texts)]  # as sent
    work = [(item, prompts, prompts_dir, use_gemini) for item in items]
    done, failing = run_items(
        f"extract_{Path(out).stem}", work, key=lambda w: dedupe_key(w[0]), fn=_extract_item,
        runner=process_runner(workers, desc="Summarize & extract"),
        failed=lambda res: bool(res.get("errors")), fp=fingerprint(prompt_texts, model))
    last = {dedupe_key(w[0]): res for w, res in failing if isinstance(res, dict)}
    results = []
    for item in items:
        k = dedupe_key(item)
        res = done.get(k) or last.get(k) or {}
        results.append({**item, 'extraction': res.get('extraction', {})})
    return results


def _extract_item(args) -> dict:
    """_process_item's answers for one paper: {"extraction": ..., "errors": {prompt: error}}.
    "errors" lists the prompts whose calls raised (API or network), which are retried; a
    prompt that answered without valid JSON is final, as before."""
    item = _process_item((dict(args[0]), *args[1:]))
    return {"extraction": item['extraction'], "errors": item.pop('_call_errors', {})}

def _process_item(args):
    """
    Helper function to process a single paper with a series of prompts.
    Includes validation and retry logic for invalid/empty JSON responses.
    """
    item, prompts, prompts_dir, use_gemini = args

    extraction_data = {}

    for prompt_name in prompts:
        prompt_path = prompts_dir / prompt_name
        if not prompt_path.exists():
            print(f"Warning: Prompt file {prompt_path} not found.")
            continue
        
        prompt_template = prompt_path.read_text(encoding="utf-8")
        if prompt_name == 'paper_classification_prompt.md':
            prompt_template = _inject_dataset_hints_into_prompt(prompt_template)
        
        # Model configurable via env; default to a lightweight general model for cost control
        if use_gemini:
            model = os.getenv('WSI_EXTRACTION_MODEL', 'gemini-2.5-pro')
        else:
            model = os.getenv('WSI_EXTRACTION_MODEL', 'gpt-6-luna')
        
        # Per-prompt retry with exponential backoff on API errors, invalid JSON, or empty responses
        attempts = int(os.getenv('WSI_LLM_RETRIES', '3'))
        wait_base = 1.0
        extracted_json = {}
        last_error = None
        raised = False  # the last attempt raised (API / network), rather than answered badly
        
        for attempt in range(attempts):
            try:
                # Use run_gpt with built-in JSON validation
                reject_all_empty = prompt_name != "dataset_details.md"
                response = run_gpt(
                    system_prompt=prompt_template,
                    user_prompt=item.get('fulltext', ''),
                    model=model,
                    item=item.get('link') or item.get('title') or "",
                    response_format={"type": "json_object"},
                    use_gemini=use_gemini,
                    validate_json=True,  # Enable JSON validation
                    reject_all_empty=reject_all_empty,
                    max_retries=1  # Let run_gpt do 1 internal retry, we do outer retries
                )
                
                content = response.choices[0].message.content
                if not content or content.strip() == "":
                    raised = False
                    last_error = "Empty response"
                    continue
                
                # Parse and validate
                is_valid, parsed, error = validate_json_response(
                    content,
                    reject_all_empty=reject_all_empty
                )
                
                raised = False
                if is_valid and parsed:
                    extracted_json = parsed
                    break
                else:
                    last_error = error
                    logger.warning(
                        f"JSON validation failed for {prompt_name} on paper "
                        f"'{item.get('title', 'unknown')[:50]}' (attempt {attempt + 1}): {error}"
                    )
                    
            except (json.JSONDecodeError, IndexError) as e:
                raised = False
                last_error = str(e)
                logger.warning(
                    f"JSON decode error for {prompt_name} on paper "
                    f"'{item.get('title', 'unknown')[:50]}' (attempt {attempt + 1}): {e}"
                )
            except Exception as e:
                raised = not is_permanent_error(e)  # a 400 (e.g. too long) won't change
                last_error = str(e)
                logger.warning(
                    f"Error extracting {prompt_name} on paper "
                    f"'{item.get('title', 'unknown')[:50]}' (attempt {attempt + 1}): {e}"
                )
            
            # Backoff before retry
            if attempt < attempts - 1:
                sleep_s = wait_base * (2 ** attempt) + random.random() * 0.25
                time.sleep(min(sleep_s, 10.0))
        
        if not extracted_json and last_error:
            logger.warning(
                f"Failed to extract {prompt_name} after {attempts} attempts on paper "
                f"'{item.get('title', 'unknown')[:50]}': {last_error}"
            )
        
        extraction_data[prompt_name] = extracted_json
        if not extracted_json and raised:
            item.setdefault('_call_errors', {})[prompt_name] = str(last_error)[:300]

    item['extraction'] = extraction_data
    return item
